#!/usr/bin/env python3
"""
[OPT-457] Shader Permutation Cooker for Neleo Engine (Nintendo Wii U CafeGLSL).
Compiles compile-time #define permutations from assets/shaders/pbr_template_gx2.frag
into compact GX2 .gsh binaries and emits include/Graphics/PBRVariantsShaderBinary.hpp
(strictly LF line endings, namespace Neleo).
"""

from __future__ import annotations

import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COMPILER = ROOT / "tools" / "cafeglsl" / "cafeglsl-1.0.0-rc1-windows-x86_64" / "bin" / "glslcompiler.exe"
SHADER_DIR = ROOT / "assets" / "shaders"
VS_PATH = SHADER_DIR / "pbr_mesh_gx2.vert"
INST_VS_PATH = SHADER_DIR / "instanced_mesh_gx2.vert"
TEMPLATE_PS_PATH = SHADER_DIR / "pbr_template_gx2.frag"
OUT_HEADER = ROOT / "include" / "Graphics" / "PBRVariantsShaderBinary.hpp"

VARIANTS = [
    ("pbr_dir_gx2",        "PBR_DIR_GX2",        VS_PATH,      {"USE_MULTILIGHT": 0, "USE_NORMAL_MAP": 0, "USE_SHADOWS": 0}),
    ("pbr_dir_bump_gx2",   "PBR_DIR_BUMP_GX2",   VS_PATH,      {"USE_MULTILIGHT": 0, "USE_NORMAL_MAP": 1, "USE_SHADOWS": 0}),
    ("pbr_multi_gx2",      "PBR_MULTI_GX2",      VS_PATH,      {"USE_MULTILIGHT": 1, "USE_NORMAL_MAP": 0, "USE_SHADOWS": 0}),
    ("pbr_multi_bump_gx2", "PBR_MULTI_BUMP_GX2", VS_PATH,      {"USE_MULTILIGHT": 1, "USE_NORMAL_MAP": 1, "USE_SHADOWS": 0}),
    ("pbr_shadow_dir_gx2", "PBR_SHADOW_DIR_GX2", VS_PATH,      {"USE_MULTILIGHT": 0, "USE_NORMAL_MAP": 1, "USE_SHADOWS": 1}),
    ("pbr_shadow_gx2",     "PBR_SHADOW_GX2",     VS_PATH,      {"USE_MULTILIGHT": 1, "USE_NORMAL_MAP": 1, "USE_SHADOWS": 1}),
    ("pbr_inst_dir_gx2",   "PBR_INST_DIR_GX2",   INST_VS_PATH, {"USE_MULTILIGHT": 0, "USE_NORMAL_MAP": 0, "USE_SHADOWS": 0}),
]


def parse_gsh_metrics(data: bytes) -> tuple[int | None, int | None, int]:
    if len(data) < 32 or data[:4] != b"Gfx2":
        return None, None, 0
    off = struct.unpack(">I", data[4:8])[0]
    vs_gprs = None
    ps_gprs = None
    ps_prog = 0
    while off + 32 <= len(data):
        magic, hsz, _maj, _minv, btype, bsz, _bidx, _resv = struct.unpack(">4sIIIIIII", data[off:off + 32])
        if magic != b"BLK{" or hsz < 32:
            break
        body_start = off + hsz
        body_end = body_start + bsz
        if body_end > len(data):
            break
        if btype == 3 and bsz >= 4:
            vs_gprs = struct.unpack(">I", data[body_start:body_start + 4])[0] & 0xFF
        elif btype == 6 and bsz >= 4:
            ps_gprs = struct.unpack(">I", data[body_start:body_start + 4])[0] & 0xFF
        elif btype == 7:
            ps_prog = bsz
        off = body_end
    return vs_gprs, ps_gprs, ps_prog


def inject_defines(source: str, defines: dict[str, int]) -> str:
    lines = source.splitlines()
    define_lines = [f"#define {k} {v}" for k, v in defines.items()]
    for idx, line in enumerate(lines):
        if line.strip().startswith("#version"):
            return "\n".join(lines[:idx + 1] + define_lines + lines[idx + 1:]) + "\n"
    return "\n".join(define_lines + lines) + "\n"


def format_c_array(sym_prefix: str, data: bytes) -> str:
    rows: list[str] = []
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        rows.append("    " + ", ".join(f"0x{b:02X}" for b in chunk))
    body = ",\n".join(rows)
    return (
        f"constexpr uint32_t {sym_prefix}_GSH_SIZE = {len(data)}u;\n"
        f"alignas(64) inline constexpr uint8_t {sym_prefix}_GSH_DATA[{len(data)}] = {{\n"
        f"{body}\n"
        f"}};\n"
    )


def main() -> int:
    if not COMPILER.exists():
        print(f"ERROR: CafeGLSL compiler not found at {COMPILER}", file=sys.stderr)
        return 1

    template_src = TEMPLATE_PS_PATH.read_text(encoding="utf-8")
    sections: list[str] = [
        "#pragma once",
        "#include <cstdint>",
        "",
        "// Auto-generated by tools/CookShaders.py from assets/shaders/pbr_template_gx2.frag",
        "// Do not edit manually. Strictly LF line endings.",
        "",
        "namespace Neleo {",
        "",
    ]

    with tempfile.TemporaryDirectory(prefix="neleo_shader_cook_") as tmpdir:
        tmp = Path(tmpdir)
        for name, sym_prefix, vs_path, defines in VARIANTS:
            ps_tmp = tmp / f"{name}.frag"
            ps_tmp.write_text(inject_defines(template_src, defines), encoding="utf-8", newline="\n")
            gsh_out = SHADER_DIR / f"{name}.gsh"

            cmd = [
                str(COMPILER),
                "--uniform-mode", "register",
                "-vs", str(vs_path),
                "-ps", str(ps_tmp),
                "-o", str(gsh_out),
            ]
            proc = subprocess.run(cmd, capture_output=True, text=True)
            if proc.returncode != 0:
                print(f"ERROR compiling {name}:\n{proc.stdout}\n{proc.stderr}", file=sys.stderr)
                return proc.returncode

            data = gsh_out.read_bytes()
            vs_gprs, ps_gprs, ps_prog = parse_gsh_metrics(data)
            print(
                f"COOKED {name + '.gsh':22s} | size={len(data):5d} B | "
                f"VS_GPR={str(vs_gprs):>2s} | PS_GPR={str(ps_gprs):>2s} | PS_PROG={ps_prog:5d} B"
            )
            sections.append(format_c_array(sym_prefix, data))

    sections.append("} // namespace Neleo")
    sections.append("")
    OUT_HEADER.write_text("\n".join(sections), encoding="utf-8", newline="\n")
    print(f"EMITTED {OUT_HEADER.relative_to(ROOT)} ({OUT_HEADER.stat().st_size:,} B)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
